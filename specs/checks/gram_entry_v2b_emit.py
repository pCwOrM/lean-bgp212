#!/usr/bin/env python3
"""Emit Solution/GramEntryCert.lean: the kernel certificate for V2b's Gram entry.

The closed form `gramFormula` (BGP212/GramEntry.lean) is mirrored here in exact rational
arithmetic (Python Fractions, standard library only). The emitted Lean file states one
`decide +kernel` lemma per row `r` (the undivided evaluation exceeds 8 GB of kernel memory) and
assembles them into `gramFormula_table3` and `gramEntryQ_eq`.

Usage: python3 -I specs/checks/gram_entry_v2b_emit.py [output path]
"""
import sys
from fractions import Fraction as Fr
from math import comb, factorial as fact

L = Fr(53, 50)
G = Fr(41, 625)
BNUM = [777, 794, 875, 917, 953, 983, 1016, 1042, 1063, 1081]


def C(m):
    """Table 3: C(m) = 4 B_{1,m}, C(0) = 0, constant from m = 10 on."""
    if m == 0:
        return Fr(0)
    return 4 * Fr(BNUM[min(m, 10) - 1], 5000)


def ws_val(r, A, j, c):
    return c ** (r + A + j) * fact(A) * fact(j) / Fr(fact(r + A + j))


def two_group(n, r, A, B, p, c, M):
    if not (c >= 0 and M >= 0):
        return Fr(0)
    q = n + B + p
    cp = min(c, M)
    return Fr(fact(B) * fact(p), fact(q)) * sum(
        comb(q, j) * (M - cp) ** (q - j) * ws_val(r, A, j, cp) for j in range(q + 1))


def H(kind, N, g, Lv, Cf, e, p, r, k):
    c = Cf(r) - r * g
    M = Lv - (r + k) * g
    tot = Fr(0)
    for t in range(e + 1):
        if kind == "in":
            v, A, B = g, t, 0
        elif kind == "k":
            v, A, B = g, 0, t
        else:
            v, A, B = Fr(0), 0, t
        tot += comb(e, t) * v ** (e - t) * two_group(N - r, r, A, B, p, c, M)
    return tot


def gram_row(N, g, Lv, Cf, e, p, r):
    s = Fr(0)
    for k in range(N - 1 - r + 1):
        sg = (-1) ** k
        s += comb(N - 1 - r, k) * (sg * H("in", N, g, Lv, Cf, e, p, r + 1, k)
                                   + sg * H("out", N, g, Lv, Cf, e, p, r, k)
                                   - sg * H("k", N, g, Lv, Cf, e, p, r, k + 1))
    return comb(N - 1, r) * s


def gram_formula(N, g, Lv, Cf, e, p):
    return sum(gram_row(N, g, Lv, Cf, e, p, r) for r in range(N - 1 + 1))


def lit(x):
    x = Fr(x)
    if x.denominator == 1:
        return f"({x.numerator} : ℚ)"
    return f"({x.numerator} / {x.denominator} : ℚ)"


