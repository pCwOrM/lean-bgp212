"""Emit the A3c Lean data from certificate JSON (outside the trusted base).

Usage, from the repository root:
  python3 -I specs/checks/packing_a3c_emit.py specs/certificates/packing_a3c.json OUTDIR
writes OUTDIR/Solution/PackingCData.lean and OUTDIR/Solution/PackingCCheck.lean. With
OUTDIR = . it regenerates the committed files; `--check` compares instead of writing and
exits nonzero on any difference."""
import json, sys, os
from fractions import Fraction as F
src, outdir = sys.argv[1], sys.argv[2]
check = "--check" in sys.argv
C = json.load(open(src))
assert C["open"] == [], "emitter expects every root proved"
HDR = '''/-
Copyright (c) 2026 thinkthoughts. All rights reserved.
Released under MIT license as described in the file LICENSE.
'''
def lam(c):
    return "[" + ", ".join(f"({j}, {F(l).numerator}, {F(l).denominator})" for j, l in c) + "]"
LEAVES = 8   # a subtree with at most this many leaves is one kernel `decide`
def nleaves(t):
    return nleaves(t["left"]) + nleaves(t["right"]) if "split" in t else 1
def term(t, ind="  "):
    if "empty" in t: return f"(.empty {lam(t['empty'])})"
    if "leaf" in t:
        return f"(.leaf {t['leaf']} [{', '.join(lam(c) for c in t['certs'])}])"
    r = F(t["rhs"])
    return (f"(.split {t['split']} ({r.numerator}) {r.denominator}\n{ind}  {term(t['left'], ind + '  ')}"
            f"\n{ind}  {term(t['right'], ind + '  ')})")
def cut(t, side):
    r = F(t["rhs"]); return f"({t['split']}, ({r.numerator}), {r.denominator}, {'true' if side else 'false'})"
defs, thms = [], []
for i, p in enumerate(C["proved"]):
    m, mp = p["m"], p["m_prime"]; n = m + mp
    nodes = []   # (name, def body, proof, path)
    def walk(t, path):
        k = len(nodes); name = f"certRowC{i}_{k}"; nodes.append(None)
        if "split" in t and nleaves(t) > LEAVES:
            l = walk(t["left"], path + [cut(t, True)]); r = walk(t["right"], path + [cut(t, False)])
            rr = F(t["rhs"])
            body = f"(.split {t['split']} ({rr.numerator}) {rr.denominator} {l} {r})"
            proof = f":=\n  checkTree2_split_path (by decide) {l}_valid {r}_valid"
        else:
            body = term(t); proof = ":= by\n  decide +kernel"
        nodes[k] = (name, body, proof, path); return name
    walk(p["tree"], [])
    for name, body, proof, path in reversed(nodes):
        defs.append(f"def {name} : Tree2 :=\n  {body}\n")
    for name, body, proof, path in reversed(nodes):
        thms.append(f"theorem {name}_valid :\n    checkTree2 {n} {n + 2} cdD (pathCell (baseCell {m} {mp} 2)\n"
                    f"      [{', '.join(path)}]) {name} = true {proof}\n")
    defs.append(f"def certRowC{i} : CertRowC := ({m}, {mp}, certRowC{i}_0)\n")
    thms.append(f"/-- (D, {m}, {mp}). -/\ntheorem certRowC{i}_valid : rowC certRowC{i} = true :=\n"
                f"  rowC_intro (by decide) (by decide) certRowC{i}_0_valid\n")
n = len(C["proved"])
data = HDR + '''Certificate data emitted by specs/checks/packing_a3c_emit.py from
specs/certificates/packing_a3c.json (generated by specs/checks/packing_a3c_generate.py).
-/
import Solution.PackingCertC

/-! # A3c certificate data: one row per (D) root left open by A3b

Each tree is stored node by node: a subtree with at most 8 leaves is one definition
(`certRowC<i>_<k>`), and every node above those is a single split naming its two children.
`certRowC<i>_0` is the root of row `i`. -/

namespace BGP212.PackingCert

''' + "\n".join(defs) + "\n/-- The A3c certificate table. -/\ndef certTableC : List CertRowC :=\n  [" + \
    ", ".join(f"certRowC{i}" for i in range(n)) + "]\n\nend BGP212.PackingCert\n"
chk = HDR + '''Emitted by specs/checks/packing_a3c_emit.py.
-/
import Solution.PackingCData

/-! # A3c: the kernel runs the verified checker on every certificate piece

Each subtree of at most 8 leaves is checked by `decide +kernel` on its own cell (the base cell
plus the cuts on its path); `checkTree2_split_path` assembles the pieces and `rowC_intro`
closes each row. -/

namespace BGP212.PackingCert

''' + "\n".join(thms) + "\nend BGP212.PackingCert\n"
files = {"Solution/PackingCData.lean": data, "Solution/PackingCCheck.lean": chk}
bad = 0
for path, text in files.items():
    full = os.path.join(outdir, path)
    if check:
        if not os.path.exists(full) or open(full).read() != text:
            print("DIFFERS:", path); bad = 1
    else:
        os.makedirs(os.path.dirname(full), exist_ok=True); open(full, "w").write(text)
if check: print("emitted files match" if not bad else "emitted files differ")
sys.exit(bad)
