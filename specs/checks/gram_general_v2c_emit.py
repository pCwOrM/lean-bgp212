#!/usr/bin/env python3
"""Emit Solution/GramGeneralCert.lean: the kernel certificate for V2c's worked example.

The worked example is the Gram entry
    I_T[(1, (2)), (0, (2))] = ∫_{T̃} (L − P₁) P₂² = 45 · F4 + 1980 · F22,
    F4  = gramFin 45 1 g L C ![4] 1      (∫ (L − Σx) x₀⁴),
    F22 = gramFin 45 2 g L C ![2, 2] 1   (∫ (L − Σx) x₀² x₁²),
at Table 3 (BGP212.Params). The closed form `gramFin` (BGP212/GramGeneral.lean) is mirrored here in
exact rational arithmetic (standard library only). Each cell `finCell … r A B` (row r, placement
(A, B) of the distinguished coordinates) is one `decide +kernel` lemma, so that each kernel
evaluation stays below about 1.5 GB above the import baseline; rows and totals are assembled by
`norm_num`.

Usage: python3 -I specs/checks/gram_general_v2c_emit.py [output path]
"""
import itertools
import sys
from fractions import Fraction as Fr
from math import comb, factorial as fact, prod

L = Fr(53, 50)
G = Fr(41, 625)
BNUM = [777, 794, 875, 917, 953, 983, 1016, 1042, 1063, 1081]
N, P = 45, 1


def C(m):
    if m == 0:
        return Fr(0)
    return 4 * Fr(BNUM[min(m, 10) - 1], 5000)


def two_group_w(n, r, A, B, p, W, c, M):
    if not (c >= 0 and M >= 0):
        return Fr(0)
    q = n + B + p
    cp = min(c, M)
    return W * Fr(fact(p), fact(q)) * sum(
        comb(q, j) * (M - cp) ** (q - j) * cp ** (r + A + j) * Fr(fact(j), fact(r + A + j))
        for j in range(q + 1))


def phi_fin(es, A, B, rho, kap):
    d = len(es)
    tot = Fr(0)
    for t in itertools.product(*[range(e + 1) for e in es]):
        coef = prod(comb(es[j], t[j]) * (G if (j in A or j in B) else Fr(0)) ** (es[j] - t[j])
                    for j in range(d))
        if coef == 0:
            continue
        a = sum(t[j] for j in A)
        b = sum(t[j] for j in range(d) if j not in A)
        W = prod(fact(x) for x in t)
        tot += coef * two_group_w(N - rho, rho, a, b, P, W, C(rho) - rho * G, L - (rho + kap) * G)
    return tot


def fin_cell(es, r, A, B):
    d = len(es)
    s = sum(comb(N - d - r, k) * (-1) ** k * phi_fin(es, A, B, len(A) + r, len(B) + k)
            for k in range(N - d - r + 1))
    return (-1) ** len(B) * comb(N - d, r) * s


def lit(x):
    x = Fr(x)
    if x.denominator == 1:
        return f"({x.numerator} : ℚ)"
    return f"({x.numerator} / {x.denominator} : ℚ)"


def fs(S):
    return "∅" if not S else "{" + ", ".join(str(j) for j in sorted(S)) + "}"


# cell order exactly as produced by `finRow_one` / `finRow_two`
CELLS = {
    1: [(set(), set()), (set(), {0}), ({0}, set())],
    2: [(set(), set()), (set(), {0}), (set(), {1}), (set(), {0, 1}),
        ({0}, set()), ({0}, {1}), ({1}, set()), ({1}, {0}), ({0, 1}, set())],
}

