"""Emit the A3b Lean data from certificate JSON (outside the trusted base).

Usage, from the repository root:
  python3 -I specs/checks/packing_a3b_emit.py specs/certificates/packing_a3b.json OUTDIR
writes OUTDIR/BGP212/PackingLedgerB.lean, OUTDIR/Solution/PackingBData.lean and
OUTDIR/Solution/PackingBCheck.lean. With OUTDIR = . it regenerates the committed files;
`--check` compares instead of writing and exits nonzero on any difference."""
import json, sys, os
from fractions import Fraction as F
src, outdir = sys.argv[1], sys.argv[2]
check = "--check" in sys.argv
C = json.load(open(src))
HDR = '''/-
Copyright (c) 2026 thinkthoughts. All rights reserved.
Released under MIT license as described in the file LICENSE.
'''
def tree(t):
    if "leaf" in t:
        certs = "[" + ", ".join("[" + ", ".join(f"({j}, {F(l).numerator}, {F(l).denominator})" for j, l in c) + "]" for c in t["certs"]) + "]"
        return f"(.leaf {t['leaf']} {certs})"
    a = "[" + ", ".join(str(F(x).numerator) for x in t["split"]) + "]"
    r = F(t["rhs"])
    return f"(.split {a} ({r.numerator}) {r.denominator}\n      {tree(t['left'])}\n      {tree(t['right'])})"
rows = []
for p in C["proved"]:
    c = p["cond"]; tr = p["trees"]
    ts = [tree(tr["A1"]), tree(tr["A2"])] if c == "A" else [tree(tr[c])]
    rows.append(f"(.{c}, {p['m']}, {p['m_prime']}, [{', '.join(ts)}])")
settled = [(p["cond"], p["m"], p["m_prime"]) for p in C["proved"]]
openB = [tuple(r) for r in C["open"]]
def lst(rs):
    items = [f"(.{c}, {m}, {mp})" for c, m, mp in rs]; lines = []; cur = "    "
    for it in items:
        if len(cur) + len(it) + 2 > 92: lines.append(cur.rstrip()); cur = "    "
        cur += it + ", "
    lines.append(cur.rstrip().rstrip(",")); return "[\n" + "\n".join(lines) + " ]"
files = {}
files["BGP212/PackingLedgerB.lean"] = HDR + f'''Source: Axiom Math, "A New Bound for Small Gaps Between Primes", preliminary draft
(September 3, 2026): Lemma 7.10 (p. 36).
-/
import BGP212.Packing

/-! # A3b ledger

`settledRootsB`: the {len(settled)} roots of A3a's `openRoots` proved in A3b. `openRootsB`: the
{len(openB)} (D) roots still open. Emitted by specs/checks/packing_a3b_emit.py from
specs/certificates/packing_a3b.json. -/

namespace BGP212.Packing

/-- The {len(settled)} roots proved in A3b. -/
def settledRootsB : List (Cond × Nat × Nat) := {lst(settled)}

/-- The {len(openB)} (D) roots open after A3b. -/
def openRootsB : List (Cond × Nat × Nat) := {lst(openB)}

end BGP212.Packing
'''
data = HDR + '''Certificate data emitted by specs/checks/packing_a3b_emit.py from
specs/certificates/packing_a3b.json (generated by specs/checks/packing_a3b_generate.py).
Untrusted: every row is re-checked by the Lean kernel through `rowB`.
-/
import Solution.PackingCert

namespace BGP212.PackingCert

open BGP212.Packing

'''
for i, r in enumerate(rows):
    data += f"def certRow{i} : CertRow :=\n  {r}\n\n"
data += f"/-- Certificate trees for the {len(rows)} roots of `settledRootsB`, in the same order. -/\n"
data += "def certTableB : List CertRow :=\n  [" + ", ".join(f"certRow{i}" for i in range(len(rows))) + "]\n\nend BGP212.PackingCert\n"
files["Solution/PackingBData.lean"] = data
chk = HDR + '''Kernel checks of the A3b certificate rows, one theorem per row.
-/
import Solution.PackingBData

namespace BGP212.PackingCert

'''
for i in range(len(rows)):
    chk += f"theorem certRow{i}_valid : rowB certRow{i} = true := by decide +kernel\n"
chk += "\nend BGP212.PackingCert\n"
files["Solution/PackingBCheck.lean"] = chk
bad = 0
for path, text in files.items():
    full = os.path.join(outdir, path)
    if check:
        same = os.path.exists(full) and open(full).read() == text
        print(("match   " if same else "DIFFERS ") + path); bad += (not same)
    else:
        os.makedirs(os.path.dirname(full), exist_ok=True); open(full, "w").write(text)
print(f"rows {len(rows)}, settled {len(settled)}, open {len(openB)}")
sys.exit(1 if bad else 0)
